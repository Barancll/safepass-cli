def valid(value):
    """True for '' (none) or a known '<shape>:<colour>'"""
    if value == '':
        return True
    if not isinstance(value, str) or value.count(':') != 1:
        return False
    shape, color = value.split(':')
    return shape in SHAPES and color in COLORS


def choices():
    """For the picker template: [(name, svg inner markup)], [(name, hex)]"""
    return {
        'shapes': [(name, mark_safe(svg)) for name, svg in SHAPES.items()],
        'colors': list(COLORS.items()),
    }
